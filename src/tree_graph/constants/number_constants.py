"""Numeric constants used throughout the library.

This module defines commonly used numeric values as named constants
for clarity and maintainability.
"""


class NumberConstants:
    """Numeric constants used throughout the library.

    These are commonly used numeric values that should be defined
    as constants for clarity.
    """

    # Zero and one (used for indexing, counting, initialization)
    ZERO: int = 0
    ONE: int = 1
    TWO: int = 2
    FIVE: int = 5
    MINUS_ONE: int = -1
    MINUS_TWO: int = -2

    # Float values (used for defaults, calculations)
    ZERO_FLOAT: float = 0.0
    ONE_FLOAT: float = 1.0
    HALF: float = 0.5
    PERCENTAGE: float = 100.0
    TENTH: float = 0.1
